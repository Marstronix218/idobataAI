import { fireEvent, render, screen } from "@testing-library/react";
import { axe } from "jest-axe";
import { beforeEach, describe, expect, it, vi } from "vitest";

vi.mock("next/link", () => ({
  default: ({ children, href, ...props }: React.ComponentProps<"a">) => (
    <a href={href} {...props}>{children}</a>
  ),
}));

import { Feed } from "@/components/social/feed";

describe("Feed", () => {
  beforeEach(() => {
    Object.defineProperty(window, "innerWidth", {
      configurable: true,
      value: 390,
    });
  });

  it("renders the community feed at a mobile viewport", () => {
    render(<Feed />);

    expect(screen.getByRole("heading", { name: "Community" })).toBeVisible();
    expect(screen.getAllByRole("article").length).toBeGreaterThan(0);
    expect(screen.getByRole("button", { name: "Show more progress" })).toBeVisible();
  });

  it("visibly labels AI companion posts", () => {
    render(<Feed />);

    expect(screen.getAllByText("AI-generated").length).toBeGreaterThan(0);
    expect(
      screen.getAllByText("This post was generated by an AI companion.").length,
    ).toBeGreaterThan(0);
  });

  it("visibly identifies AI companion reactions", () => {
    render(<Feed />);

    expect(screen.getAllByText(/\d+ AI/).length).toBeGreaterThan(0);
  });

  it("visibly labels owner posts as public", () => {
    render(<Feed />);

    expect(screen.getAllByText("Public").length).toBeGreaterThan(0);
  });

  it("exposes reaction state with aria-pressed", () => {
    render(<Feed />);
    const cheer = screen.getAllByRole("button", { name: /Cheer/ })[0];

    expect(cheer).toHaveAttribute("aria-pressed", "false");
    fireEvent.click(cheer);

    expect(cheer).toHaveAttribute("aria-pressed", "true");
  });

  it("announces a saved reaction to assistive technology", () => {
    render(<Feed />);
    const cheer = screen.getAllByRole("button", { name: /Cheer/ })[0];

    fireEvent.click(cheer);

    expect(screen.getByText("Cheer reaction saved.")).toBeInTheDocument();
  });

  it("filters the feed to the owner posts", () => {
    render(<Feed />);
    fireEvent.click(screen.getByRole("button", { name: "My posts" }));

    expect(screen.getAllByRole("article")).toHaveLength(1);
    expect(screen.getByText("Mina Park")).toBeVisible();
  });

  it("has no automated accessibility violations", async () => {
    const { container } = render(<Feed />);

    expect(await axe(container)).toHaveNoViolations();
  });
});
